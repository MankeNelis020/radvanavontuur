import type { Accessibility, EngineDestination, Entrance, Scale } from "@/domain/types";

export type CatalogDestination = EngineDestination & {
  roles: ("adventure" | "lunch")[];
  osmRef: string;
};

const unknownAccess: Accessibility = {
  wheelchair: null,
  buggy: null,
  stroller: null,
  limitedWalking: null,
  stairsFree: null,
};

const unknownPrice: Entrance = {
  model: "unknown",
  note: "Geen betrouwbare actuele prijs in de catalogus.",
};

type Seed = {
  id: string;
  name: string;
  category: string;
  interests: string[];
  latitude: number;
  longitude: number;
  address: string;
  locality: string;
  description: string;
  minimumAgeMonths?: number | null;
  maximumAgeMonths?: number | null;
  ageSuitabilityNote: string;
  accessibility?: Partial<Accessibility>;
  activityLevel: Scale;
  relaxationAdventure: Scale;
  environment: EngineDestination["environment"];
  familiarity: Scale;
  estimatedDurationMinutes: number;
  entrance?: Entrance;
  roles?: ("adventure" | "lunch")[];
  osmRef: string;
  safetyRestrictions?: string[];
};

function place(seed: Seed): CatalogDestination {
  const osmUrl = `https://www.openstreetmap.org/${seed.osmRef}`;
  return {
    id: seed.id,
    name: seed.name,
    category: seed.category,
    interests: seed.interests,
    latitude: seed.latitude,
    longitude: seed.longitude,
    address: seed.address,
    locality: seed.locality,
    description: seed.description,
    minimumAgeMonths: seed.minimumAgeMonths ?? 0,
    maximumAgeMonths: seed.maximumAgeMonths ?? null,
    ageSuitabilityKnown: true,
    ageSuitabilityNote: seed.ageSuitabilityNote,
    accessibility: { ...unknownAccess, ...seed.accessibility },
    activityLevel: seed.activityLevel,
    relaxationAdventure: seed.relaxationAdventure,
    environment: seed.environment,
    familiarity: seed.familiarity,
    estimatedDurationMinutes: seed.estimatedDurationMinutes,
    entrance: seed.entrance ?? unknownPrice,
    openingHours: null,
    providerPlaceId: null,
    website: null,
    imageUrl: null,
    sourceUrl: osmUrl,
    coordinateSource: `OpenStreetMap ${seed.osmRef}, © OpenStreetMap-bijdragers, ODbL`,
    verificationStatus: "editorial",
    safetyRestrictions: seed.safetyRestrictions ?? [],
    roles: seed.roles ?? ["adventure"],
    osmRef: seed.osmRef,
  };
}

